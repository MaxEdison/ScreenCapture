def make_translator(lang):
    table, fallback = STRINGS.get(lang, STRINGS["en"]), STRINGS["en"]

    def tr(key, **fmt):
        text = table.get(key) or fallback.get(key, key)
        return text.format(**fmt) if fmt else text

    return tr
